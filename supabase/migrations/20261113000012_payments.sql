-- Online deposit payments (Moyasar test mode / fake provider). Additive.
--   * payments gets an unguessable public token (the pay-page URL), the provider's checkout url,
--     the provider's payment id and a 'refund_due' status (paid after the hold was lost).
--   * payment_events: one row per provider event id, for idempotent webhook handling.
--   * settle_payment(): the ONE place that marks a payment paid and confirms the appointment,
--     atomically. service_role only (the webhook route and the fake provider call it).

alter table public.payments
  add column if not exists public_token         text,
  add column if not exists provider_payment_id  text,
  add column if not exists checkout_url         text,
  add column if not exists review_reason        text,
  add column if not exists paid_at              timestamptz;

-- 48+ random chars generated by the app (crypto.randomBytes); never sequential, never the customer token.
alter table public.payments drop constraint if exists payments_public_token_len;
alter table public.payments add constraint payments_public_token_len
  check (public_token is null or length(public_token) between 32 and 128);
create unique index if not exists payments_public_token_uq on public.payments(public_token) where public_token is not null;

alter table public.payments drop constraint if exists payments_status_check;
alter table public.payments add constraint payments_status_check
  check (status in ('pending','paid','failed','refunded','refund_due'));

create table if not exists public.payment_events (
  provider    text not null,
  event_id    text not null,
  tenant_id   uuid not null references public.tenants(id) on delete cascade,
  payment_id  uuid references public.payments(id) on delete cascade,
  type        text not null,
  outcome     text,
  received_at timestamptz not null default now(),
  primary key (provider, event_id)
);
create index if not exists payment_events_payment_idx on public.payment_events(payment_id);
alter table public.payment_events enable row level security;
-- no policies and no grants: only service_role (bypasses RLS) touches it
revoke all on public.payment_events from anon, authenticated;

-- p_outcome: 'paid' | 'failed'. p_amount_minor / p_currency are what the PROVIDER's API reported.
-- Returns one of: duplicate | confirmed | confirmed_after_expiry | refund_due | amount_mismatch |
--                 already_paid | failed | not_found
create or replace function public.settle_payment(
  p_payment_id          uuid,
  p_provider            text,
  p_event_id            text,
  p_event_type          text,
  p_outcome             text,
  p_provider_payment_id text,
  p_amount_minor        bigint,
  p_currency            text
) returns text
language plpgsql volatile security definer
set search_path = ''
as $$
declare
  v_pay  public.payments%rowtype;
  v_appt public.appointments%rowtype;
  v_res  text;
begin
  if p_outcome not in ('paid','failed') then raise exception 'invalid_outcome'; end if;

  select * into v_pay from public.payments where id = p_payment_id for update;
  if not found then return 'not_found'; end if;

  -- idempotency: a replayed event id is a no-op
  insert into public.payment_events (provider, event_id, tenant_id, payment_id, type)
  values (p_provider, p_event_id, v_pay.tenant_id, v_pay.id, left(p_event_type, 64))
  on conflict (provider, event_id) do nothing;
  if not found then return 'duplicate'; end if;

  if p_outcome = 'failed' then
    -- keep the hold until it expires; a later successful retry on the same invoice is still accepted
    if v_pay.status = 'pending' then
      update public.payments set status = 'failed', provider_payment_id = coalesce(provider_payment_id, p_provider_payment_id)
       where id = v_pay.id;
    end if;
    v_res := case when v_pay.status = 'paid' then 'already_paid' else 'failed' end;
    update public.payment_events set outcome = v_res where provider = p_provider and event_id = p_event_id;
    return v_res;
  end if;

  if v_pay.status in ('paid','refund_due','refunded') then
    update public.payment_events set outcome = 'already_paid' where provider = p_provider and event_id = p_event_id;
    return 'already_paid';
  end if;

  -- defence in depth: the app already compared these with the provider's API response
  if p_amount_minor is distinct from round(v_pay.amount * 100)::bigint
     or upper(coalesce(p_currency, '')) <> upper(v_pay.currency) then
    update public.payments
       set status = 'refund_due', review_reason = 'amount_mismatch',
           provider_payment_id = coalesce(provider_payment_id, p_provider_payment_id), paid_at = now()
     where id = v_pay.id;
    update public.payment_events set outcome = 'amount_mismatch' where provider = p_provider and event_id = p_event_id;
    return 'amount_mismatch';
  end if;

  select * into v_appt from public.appointments
   where id = v_pay.appointment_id and tenant_id = v_pay.tenant_id for update;

  if v_appt.status = 'pending_payment' then
    update public.appointments set status = 'confirmed', payment_expires_at = null where id = v_appt.id;
    v_res := 'confirmed';
  elsif v_appt.status = 'cancelled' then
    -- the hold expired. Try to take the slot back; the exclusion constraint refuses if it was re-booked.
    begin
      update public.appointments set status = 'confirmed', payment_expires_at = null where id = v_appt.id;
      v_res := 'confirmed_after_expiry';
    exception when exclusion_violation then
      v_res := 'refund_due';
    end;
  else
    v_res := 'refund_due';   -- confirmed/completed/no_show already: the money has no booking to pay for
  end if;

  if v_res = 'refund_due' then
    update public.payments
       set status = 'refund_due', review_reason = 'slot_unavailable_after_payment',
           provider_payment_id = coalesce(provider_payment_id, p_provider_payment_id), paid_at = now()
     where id = v_pay.id;
  else
    update public.payments
       set status = 'paid', provider_payment_id = coalesce(provider_payment_id, p_provider_payment_id), paid_at = now()
     where id = v_pay.id;
  end if;
  update public.payment_events set outcome = v_res where provider = p_provider and event_id = p_event_id;
  return v_res;
end $$;

revoke all on function public.settle_payment(uuid, text, text, text, text, text, bigint, text) from public, anon, authenticated;
grant execute on function public.settle_payment(uuid, text, text, text, text, text, bigint, text) to service_role;
comment on function public.settle_payment(uuid, text, text, text, text, text, bigint, text)
  is 'service_role only. Atomically marks a payment paid/failed and confirms the appointment; idempotent per (provider, event_id).';
